import os
import torch
import numpy as np
import PIL.Image
from PIL.ImageOps import exif_transpose
import torchvision.transforms as tvf

os.environ["OPENCV_IO_ENABLE_OPENEXR"] = "1"
import cv2  # noqa

try:
    from pillow_heif import register_heif_opener  # noqa

    register_heif_opener()
    heif_support_enabled = True
except ImportError:
    heif_support_enabled = False

ImgNorm = tvf.Compose([tvf.ToTensor(), tvf.Normalize((0.5, 0.5, 0.5), (0.5, 0.5, 0.5))])


def _imread_exr_native(path):
    """Load an EXR depth map using the OpenEXR Python bindings (works even when
    opencv-python-headless was compiled without OpenEXR support)."""
    try:
        import OpenEXR
        import Imath
        f = OpenEXR.InputFile(str(path))
        header = f.header()
        dw = header['dataWindow']
        h = dw.max.y - dw.min.y + 1
        w = dw.max.x - dw.min.x + 1
        pt = Imath.PixelType(Imath.PixelType.FLOAT)
        ch = next(iter(header['channels']))  # first available channel
        raw = f.channel(ch, pt)
        # .copy() is required, not an optimisation to drop: np.frombuffer over
        # an immutable bytes object is a read-only view that does not own its
        # data, while every caller treats this like cv2.imread's result and
        # writes into it -- e.g. threedkb.py's `depthmap[depthmap > 20000] = 0`,
        # which raises "assignment destination is read-only" on every sample.
        return np.frombuffer(raw, dtype=np.float32).reshape(h, w).copy()
    except Exception:
        return None


def img_to_arr(img):
    if isinstance(img, str):
        img = imread_cv2(img)
    return img


# Returning a black dummy image for an unreadable file silently feeds an
# all-zero point map into the loss, where safe_norm/normalize_pointcloud turn
# it into nan gradients -- a corrupt file becomes a dead model with no error
# anywhere. Raising instead is safe: BaseMultiViewDataset.__getitem__ catches
# it and resamples another index (bounded at 20 retries). Set
# CUT3R_ALLOW_DUMMY_IMAGES=1 to restore the old permissive behaviour.
_ALLOW_DUMMY_IMAGES = os.environ.get("CUT3R_ALLOW_DUMMY_IMAGES", "0") == "1"


def _dummy_or_raise(path, options=None):
    """Either raise for an unreadable image, or build the legacy black dummy."""
    detail = f"image={path}" + (f" with {options=}" if options is not None else "")
    if not _ALLOW_DUMMY_IMAGES:
        raise OSError(
            f"Could not load {detail}. The file is missing or corrupt. "
            f"(Set CUT3R_ALLOW_DUMMY_IMAGES=1 to substitute a black image "
            f"instead, but note that this injects nan into the loss.)"
        )
    print(f"WARNING: Could not load {detail}. Returning dummy black image.")
    is_single_channel = options is None or (
        options in (cv2.IMREAD_GRAYSCALE, cv2.IMREAD_ANYDEPTH)
        or "depth" in path.lower()
        or "mask" in path.lower()
    )
    if is_single_channel:
        return np.zeros((480, 640), dtype=np.float32)
    return np.zeros((480, 640, 3), dtype=np.uint8)


def imread_cv2(path, options=cv2.IMREAD_COLOR):
    """Open an image or a depthmap with opencv-python."""
    if path.endswith((".exr", "EXR")):
        img = _imread_exr_native(path)
        if img is not None:
            return img
        # fallback: cv2 (requires OpenEXR-enabled build)
        img = cv2.imread(path, cv2.IMREAD_ANYDEPTH)
        if img is None:
            return _dummy_or_raise(path)
        return img
    img = cv2.imread(path, options)
    if img is None:
        img = _dummy_or_raise(path, options)
    if img.ndim == 3:
        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    return img


def rgb(ftensor, true_shape=None):
    if isinstance(ftensor, list):
        return [rgb(x, true_shape=true_shape) for x in ftensor]
    if isinstance(ftensor, torch.Tensor):
        ftensor = ftensor.detach().cpu().numpy()  # H,W,3
    if ftensor.ndim == 3 and ftensor.shape[0] == 3:
        ftensor = ftensor.transpose(1, 2, 0)
    elif ftensor.ndim == 4 and ftensor.shape[1] == 3:
        ftensor = ftensor.transpose(0, 2, 3, 1)
    if true_shape is not None:
        H, W = true_shape
        ftensor = ftensor[:H, :W]
    if ftensor.dtype == np.uint8:
        img = np.float32(ftensor) / 255
    else:
        img = (ftensor * 0.5) + 0.5
    return img.clip(min=0, max=1)


def _resize_pil_image(img, long_edge_size):
    S = max(img.size)
    if S > long_edge_size:
        interp = PIL.Image.LANCZOS
    elif S <= long_edge_size:
        interp = PIL.Image.BICUBIC
    new_size = tuple(int(round(x * long_edge_size / S)) for x in img.size)
    return img.resize(new_size, interp)


def load_images(folder_or_list, size, square_ok=False, verbose=True):
    """open and convert all images in a list or folder to proper input format for DUSt3R"""
    if isinstance(folder_or_list, str):
        if verbose:
            print(f">> Loading images from {folder_or_list}")
        root, folder_content = folder_or_list, sorted(os.listdir(folder_or_list))

    elif isinstance(folder_or_list, list):
        if verbose:
            print(f">> Loading a list of {len(folder_or_list)} images")
        root, folder_content = "", folder_or_list

    else:
        raise ValueError(f"bad {folder_or_list=} ({type(folder_or_list)})")

    supported_images_extensions = [".jpg", ".jpeg", ".png", ".bmp"]
    if heif_support_enabled:
        supported_images_extensions += [".heic", ".heif"]
    supported_images_extensions = tuple(supported_images_extensions)

    imgs = []
    for path in folder_content:
        if not path.lower().endswith(supported_images_extensions):
            continue
        img = exif_transpose(PIL.Image.open(os.path.join(root, path))).convert("RGB")
        W1, H1 = img.size
        if size == 224:

            img = _resize_pil_image(img, round(size * max(W1 / H1, H1 / W1)))
        else:

            img = _resize_pil_image(img, size)
        W, H = img.size
        cx, cy = W // 2, H // 2
        if size == 224:
            half = min(cx, cy)
            img = img.crop((cx - half, cy - half, cx + half, cy + half))
        else:
            halfw, halfh = ((2 * cx) // 16) * 8, ((2 * cy) // 16) * 8
            if not (square_ok) and W == H:
                halfh = 3 * halfw / 4
            img = img.crop((cx - halfw, cy - halfh, cx + halfw, cy + halfh))

        W2, H2 = img.size
        if verbose:
            print(f" - adding {path} with resolution {W1}x{H1} --> {W2}x{H2}")
        imgs.append(
            dict(
                img=ImgNorm(img)[None],
                true_shape=np.int32([img.size[::-1]]),
                idx=len(imgs),
                instance=str(len(imgs)),
            )
        )

    assert imgs, "no images foud at " + root
    if verbose:
        print(f" (Found {len(imgs)} images)")
    return imgs


def load_images_for_eval(
    folder_or_list, size, square_ok=False, verbose=True, crop=True
):
    """open and convert all images in a list or folder to proper input format for DUSt3R"""
    if isinstance(folder_or_list, str):
        if verbose:
            print(f">> Loading images from {folder_or_list}")
        root, folder_content = folder_or_list, sorted(os.listdir(folder_or_list))

    elif isinstance(folder_or_list, list):
        if verbose:
            print(f">> Loading a list of {len(folder_or_list)} images")
        root, folder_content = "", folder_or_list

    else:
        raise ValueError(f"bad {folder_or_list=} ({type(folder_or_list)})")

    supported_images_extensions = [".jpg", ".jpeg", ".png"]
    if heif_support_enabled:
        supported_images_extensions += [".heic", ".heif"]
    supported_images_extensions = tuple(supported_images_extensions)

    imgs = []
    for path in folder_content:
        if not path.lower().endswith(supported_images_extensions):
            continue
        img = exif_transpose(PIL.Image.open(os.path.join(root, path))).convert("RGB")
        W1, H1 = img.size
        if size == 224:
            # resize short side to 224 (then crop)
            img = _resize_pil_image(img, round(size * max(W1 / H1, H1 / W1)))
        else:
            # resize long side to 512
            img = _resize_pil_image(img, size)
        W, H = img.size
        cx, cy = W // 2, H // 2
        if size == 224:
            half = min(cx, cy)
            if crop:
                img = img.crop((cx - half, cy - half, cx + half, cy + half))
            else:  # resize
                img = img.resize((2 * half, 2 * half), PIL.Image.LANCZOS)
        else:
            halfw, halfh = ((2 * cx) // 16) * 8, ((2 * cy) // 16) * 8
            if not (square_ok) and W == H:
                halfh = 3 * halfw / 4
            if crop:
                img = img.crop((cx - halfw, cy - halfh, cx + halfw, cy + halfh))
            else:  # resize
                img = img.resize((2 * halfw, 2 * halfh), PIL.Image.LANCZOS)
        W2, H2 = img.size
        if verbose:
            print(f" - adding {path} with resolution {W1}x{H1} --> {W2}x{H2}")
        imgs.append(
            dict(
                img=ImgNorm(img)[None],
                true_shape=np.int32([img.size[::-1]]),
                idx=len(imgs),
                instance=str(len(imgs)),
            )
        )

    assert imgs, "no images foud at " + root
    if verbose:
        print(f" (Found {len(imgs)} images)")
    return imgs


